def matches(kb, rule: Rule) -> list:
    """Наборы значений переменных, при которых правило применимо к базе"""
    bindings = kb.query(rule.conditions)
    if rule.test is not None:
        bindings = [b for b in bindings if rule.test(b)]
    return bindings


